import fs from "fs"
import path from "path"

// Read the built Astro HTML
const builtPath = path.join(process.cwd(), "dist-astro", "index.html")
let html = fs.readFileSync(builtPath, "utf-8")

type EmbeddedAsset = { encoding: "utf8" | "base64"; data: string }

function contentEncodingForFile(fileName: string): EmbeddedAsset["encoding"] {
  if (fileName.endsWith(".js")) return "utf8"
  if (fileName.endsWith(".css")) return "utf8"
  if (fileName.endsWith(".map")) return "utf8"
  if (fileName.endsWith(".html")) return "utf8"
  return "base64"
}

// Read all built assets so the Worker can serve /_astro/* requests.
const astroDir = path.join(process.cwd(), "dist-astro", "_astro")
const assetEntries: Array<[string, EmbeddedAsset]> = []
if (fs.existsSync(astroDir)) {
  for (const fileName of fs.readdirSync(astroDir)) {
    const filePath = path.join(astroDir, fileName)
    if (!fs.statSync(filePath).isFile()) continue
    const urlPath = `/_astro/${fileName}`
    const encoding = contentEncodingForFile(fileName)
    const buf = fs.readFileSync(filePath)
    const data = encoding === "utf8" ? buf.toString("utf8") : buf.toString("base64")
    assetEntries.push([urlPath, { encoding, data }])
  }
}

// Also embed root-level static assets from public/ (favicon, images, etc.)
// Astro copies these into dist-astro/ at build time.
const distRoot = path.join(process.cwd(), "dist-astro")
for (const fileName of fs.readdirSync(distRoot)) {
  const filePath = path.join(distRoot, fileName)
  if (!fs.statSync(filePath).isFile()) continue
  if (fileName === "index.html") continue
  if (fileName === "_headers") continue
  if (fileName === "_redirects") continue
  if (fileName === "_routes.json") continue

  const urlPath = `/${fileName}`
  const encoding = contentEncodingForFile(fileName)
  const buf = fs.readFileSync(filePath)
  const data = encoding === "utf8" ? buf.toString("utf8") : buf.toString("base64")
  assetEntries.push([urlPath, { encoding, data }])
}

// Find all CSS links and inline them
const linkRegex = /<link[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g
html = html.replace(linkRegex, (match, href) => {
  try {
    // href will typically be something like "/_astro/index.D9IDFaEh.css"
    // We need to resolve it relative to the dist-astro directory
    const cssPath = path.join(process.cwd(), "dist-astro", href.replace(/^\//, ''))
    if (fs.existsSync(cssPath)) {
      const cssContent = fs.readFileSync(cssPath, "utf-8")
      return `<style>${cssContent}</style>`
    }
  } catch (e) {
    console.warn(`Failed to inline CSS for ${href}`, e)
  }
  return match
})

// Also find and inline scripts just in case Astro extracts them
const scriptRegex = /<script[^>]*type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g
html = html.replace(scriptRegex, (match, src) => {
  try {
    const scriptPath = path.join(process.cwd(), "dist-astro", src.replace(/^\//, ''))
    if (fs.existsSync(scriptPath)) {
      const scriptContent = fs.readFileSync(scriptPath, "utf-8")
      return `<script type="module">${scriptContent}</script>`
    }
  } catch (e) {
    console.warn(`Failed to inline JS for ${src}`, e)
  }
  return match
})


// Escape HTML for TypeScript string literal
const escaped = html
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$/g, "\\$")

// Generate landing.ts with embedded HTML
const output = `// Auto-generated by scripts/embed-landing.ts
// Do not edit manually

export const LANDING_HTML = \`${escaped}\`
`

fs.writeFileSync(path.join(process.cwd(), "src", "landing.ts"), output)

const assetsOutput = `// Auto-generated by scripts/embed-landing.ts
// Do not edit manually

export type EmbeddedAsset = { encoding: "utf8" | "base64"; data: string }

export const LANDING_ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(Object.fromEntries(assetEntries))} as const
`

fs.writeFileSync(path.join(process.cwd(), "src", "landing-assets.ts"), assetsOutput)
console.log("embedded astro landing page into src/landing.ts and assets into src/landing-assets.ts")
